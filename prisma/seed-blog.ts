async function main() {
  console.log("🌱 Seeding 3 real launch blog posts...\n");

  for (const post of posts) {
    const existing = await prisma.blogPost.findUnique({ where: { slug: post.slug } });
    if (existing) {
      console.log(`⏭  تخطّي "${post.titleAr}" — الـslug موجود مسبقاً`);
      continue;
    }
    await prisma.blogPost.create({
      data: {
        ...post,
        isPublished: true,
        isFeatured: false,
        publishedAt: new Date(),
      },
    });
    console.log(`✅ أُضيف: ${post.titleAr}`);
  }

  console.log("\n🌱 اكتمل إدخال المقالات.");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
